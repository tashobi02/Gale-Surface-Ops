#!/usr/bin/env python3
"""Regenerate the progress block of README.md from docs/tasks/status.md.

Usage: python3 scripts/update_progress.py [--check]

Reads the subtask register in docs/tasks/_coordination.md (ids, titles, types, tags) and the rows of
docs/tasks/status.md (`| T00.01 | done | date | evidence |`; states: done, wip), then rewrites the text
between the markers <!-- progress:start --> and <!-- progress:end --> in README.md.
Fallback subtasks and desirables are left out of the totals (they may never run); a done one is
counted in the "extra" line. --check changes nothing and exits 1 if the README block is stale or
status.md names an unknown id, a bad state or a duplicate. Standard library only.
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import check_tasks  # noqa: E402  (same folder; reuses the register parser)

ROOT = Path(__file__).resolve().parent.parent
TASKS = ROOT / "docs" / "tasks"
README = ROOT / "README.md"
START, END = "<!-- progress:start -->", "<!-- progress:end -->"
STATES = ("done", "wip")
WIDTH = 20


def bar(done, total, width=WIDTH):
    filled = round(width * done / total) if total else 0
    return "█" * filled + "░" * (width - filled)


def pct(done, total):
    return f"{100 * done / total:.0f} %" if total else "—"


def read_status(reg, problems):
    state = {}
    for line in (TASKS / "status.md").read_text().splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 2 and re.fullmatch(r"T\d\d\.\d\d", cells[0]):
            sid, st = cells[0], cells[1]
            if sid not in reg:
                problems.append(f"status.md: unknown subtask {sid}")
            elif st not in STATES:
                problems.append(f"status.md: {sid} has state '{st}' (use done or wip)")
            elif sid in state:
                problems.append(f"status.md: duplicate row for {sid}")
            else:
                state[sid] = st
    return state


def render(reg, state):
    titles = {}
    for line in (TASKS / "README.md").read_text().splitlines():
        m = re.match(r"\| (TASK-\d\d) \| \[(.+?)\]", line)
        if m:
            titles[m.group(1)[5:]] = m.group(2)
    counted = {s: r for s, r in reg.items() if r["type"] != "fallback" and "desirable" not in r["tag"]}
    extra = [s for s in reg if s not in counted]
    done = sum(1 for s in counted if state.get(s) == "done")
    wip = sum(1 for s in counted if state.get(s) == "wip")
    extra_done = sum(1 for s in extra if state.get(s) == "done")
    out = [
        f"`{bar(done, len(counted))}` **{pct(done, len(counted))}** — {done} of {len(counted)} subtasks done"
        f", {wip} in progress.",
        "",
        "| Task | Progress | Done | In progress | Total |",
        "| --- | --- | --- | --- | --- |",
    ]
    for tn in sorted({s[1:3] for s in counted}):
        ids = [s for s in counted if s[1:3] == tn]
        d = sum(1 for s in ids if state.get(s) == "done")
        w = sum(1 for s in ids if state.get(s) == "wip")
        label = f"TASK-{tn} {titles.get(tn, '')}".strip()
        link = f"[{label}](docs/tasks/{next(p.name for p in TASKS.glob(f'TASK-{tn}_*.md'))})"
        out.append(f"| {link} | `{bar(d, len(ids), 10)}` {pct(d, len(ids))} | {d} | {w} | {len(ids)} |")
    out += [
        "",
        f"Totals leave out {len(extra)} fallback and desirable subtasks (they may never run); "
        f"{extra_done} of them done. Source: [docs/tasks/status.md](docs/tasks/status.md), "
        "regenerated by `make progress`.",
    ]
    return "\n".join(out)


def main(argv):
    problems = []
    reg = check_tasks.register((TASKS / "_coordination.md").read_text())
    state = read_status(reg, problems)
    text = README.read_text()
    if START not in text or END not in text:
        problems.append(f"README.md: missing {START} / {END} markers")
    if problems:
        print("\n".join(problems))
        return 1
    head, rest = text.split(START, 1)
    tail = rest.split(END, 1)[1]
    new = f"{head}{START}\n{render(reg, state)}\n{END}{tail}"
    if "--check" in argv:
        if new != text:
            print("README.md progress block is stale: run `make progress` and commit the result")
            return 1
        return 0
    README.write_text(new)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
