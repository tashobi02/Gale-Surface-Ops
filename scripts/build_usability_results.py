#!/usr/bin/env python3
"""Generate docs/ops/usability-results.md from Playwright heuristic output.

Reads `apps/web/e2e/out/usability-metrics.json` written by
`apps/web/e2e/checks/usability.spec.ts` so every number, target measurement,
wait duration, and finding in `docs/ops/usability-results.md` comes directly
from an executed Chromium run (never hand-typed).

Every rendered value carries `data-provenance` (one of
`measured|derived|modelled|assumed|replayed|simulated`, never `"live"`) and
`data-source`, and a missing value renders as the em dash `—` with
`data-unavailable="true"` (04 §D.1: a value the run did not produce says so).
"""
from __future__ import annotations

import html
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
METRICS_PATH = ROOT / "apps" / "web" / "e2e" / "out" / "usability-metrics.json"
OUT_PATH = ROOT / "docs" / "ops" / "usability-results.md"

# The app-wide convention for a value that was not produced (04 §D.1): the em dash, marked unavailable.
MISSING = "—"

ALLOWED_PROVENANCE = {"measured", "derived", "modelled", "assumed", "replayed", "simulated"}
CASE_ORDER = [
    "briefing-5-min",
    "UT-1",
    "UT-2",
    "UT-3",
    "UT-4",
    "UT-5",
    "UT-6",
    "UT-7",
    "UT-8",
    "UT-9",
]


def fmt_val(entry: dict) -> str:
    prov = str(entry.get("provenance", "assumed"))
    if prov not in ALLOWED_PROVENANCE:
        raise ValueError(f"Invalid provenance class {prov!r} (never 'live').")
    src = str(entry.get("source", "e2e:usability.spec.ts"))
    raw = entry.get("value")
    unit = entry.get("unit", "")
    if raw is None or raw == "":
        # A value the run did not produce says so (04 §D.1): the em dash, marked unavailable.
        return (
            f'<span data-provenance="{html.escape(prov, quote=True)}" '
            f'data-source="{html.escape(src, quote=True)}" '
            f'data-unavailable="true">{MISSING}</span>'
        )
    if isinstance(raw, bool):
        display = "yes" if raw else "no"
    else:
        display = f"{raw} {unit}".strip() if unit else str(raw)
    return (
        f'<span data-provenance="{html.escape(prov, quote=True)}" '
        f'data-source="{html.escape(src, quote=True)}">{html.escape(display)}</span>'
    )


def build_markdown(data: dict) -> str:
    cases: dict = data.get("cases", {})
    ordered_ids = [cid for cid in CASE_ORDER if cid in cases] + [
        cid for cid in sorted(cases) if cid not in CASE_ORDER
    ]
    if not ordered_ids:
        raise ValueError(f"No usability cases found in {METRICS_PATH}.")

    passed_count = sum(1 for cid in ordered_ids if cases[cid].get("status") == "pass")
    total_count = len(ordered_ids)
    findings_rows: list[tuple[str, str, str]] = []

    lines: list[str] = [
        "# Usability Heuristic Results (`T15.02` / `T15.03`)",
        "",
        "<!-- Generated by scripts/build_usability_results.py from apps/web/e2e/out/usability-metrics.json. Never hand-edit numbers. -->",
        "",
        f"Generated from `apps/web/e2e/checks/usability.spec.ts` on `{METRICS_PATH.relative_to(ROOT).as_posix()}` "
        f"(<span data-provenance=\"derived\" data-source=\"e2e:usability.spec.ts\">{passed_count}/{total_count}</span> automated cases passing).",
        "Every rendered measurement carries `data-provenance` (`measured|derived|modelled|assumed|replayed|simulated`) and `data-source`; a value the run did not produce renders as `—` with `data-unavailable=\"true\"`.",
        "",
        "## Automated heuristic summary",
        "",
        "| Case | Spec ref | Viewport | Result | Steps / budget | Duration | Worker wait | Min target | Min gap | Key / focus / names / error | No orange | Notes |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]

    for cid in ordered_ids:
        c = cases[cid]
        status_word = "PASS" if c.get("status") == "pass" else "FAIL"
        status_span = fmt_val({"value": status_word, "provenance": "measured", "source": "e2e:usability.spec.ts"})
        steps_str = f"{fmt_val(c['steps'])} / {fmt_val(c['stepBudget'])}"
        dur_str = fmt_val(c["durationMs"])
        wait_str = fmt_val(c["workerWaitMs"])
        targ_str = fmt_val(c["minTargetPx"])
        gap_str = fmt_val(c["minGapPx"])
        a11y_str = (
            f"key:{fmt_val(c['keyboardReachable'])} "
            f"focus:{fmt_val(c['focusVisible'])} "
            f"name:{fmt_val(c['accessibleNamesOk'])} "
            f"err:{fmt_val(c['errorGuidanceOk'])}"
        )
        orange_str = fmt_val(c["noBrandOrange"])
        notes = html.escape(str(c.get("notes") or MISSING)).replace("|", "\\|")
        spec_ref = html.escape(str(c.get("specRef") or MISSING)).replace("|", "\\|")
        vp = html.escape(str(c.get("viewport") or MISSING)).replace("|", "\\|")
        lines.append(
            f"| `{cid}` | {spec_ref} | {vp} | {status_span} | {steps_str} | {dur_str} | {wait_str} | {targ_str} | {gap_str} | {a11y_str} | {orange_str} | {notes} |"
        )
        for f in c.get("findings", []):
            findings_rows.append((cid, "automated-failure", str(f)))

    lines.extend(
        [
            "",
            "## Unautomatable human and physical criteria",
            "",
            "These `TASK-15` criteria require real humans or physical hardware (`T15.02` stays `wip` until verified manually):",
            "",
            "| Case | Human / physical criterion still required | Provenance class | Source |",
            "| --- | --- | --- | --- |",
        ]
    )
    for cid in ordered_ids:
        c = cases[cid]
        crit = html.escape(str(c.get("unautomatable") or MISSING)).replace("|", "\\|")
        lines.append(
            f"| `{cid}` | {crit} | `assumed` | `spec:TASK-15` |"
        )

    lines.extend(
        [
            "",
            "## Findings and triage (`T15.03`)",
            "",
            "| Case | Kind | Detail | Provenance |",
            "| --- | --- | --- | --- |",
        ]
    )
    if findings_rows:
        for cid, kind, detail in findings_rows:
            lines.append(
                f"| `{cid}` | `{kind}` | {html.escape(detail).replace('|', '\\|')} | `measured` (`e2e:usability.spec.ts`) |"
            )
    else:
        lines.append(
            "| `all` | `automated-gate` | Zero blocking automated heuristic failures recorded (`"
            f"{passed_count}/{total_count}"
            "` passing). Non-blocking scope notes: `briefing-5-min` uses `?site=mock_site` pending `N-140` (`gale_boxwork` landing grid); "
            "`UT-8` skip-reason control label identifies current reason without task text (`StopTaskList.tsx`); `B-04` mobile planner drawer overlap remains tracked in backend/frontend needs. | `measured` (`e2e:usability.spec.ts`) |"
        )

    lines.append("")
    return "\n".join(lines)


def main() -> int:
    if not METRICS_PATH.exists():
        print(f"Missing {METRICS_PATH}; run `E2E_PORT=8120 make e2e-one CHECK=usability` first.", file=sys.stderr)
        return 1
    data = json.loads(METRICS_PATH.read_text(encoding="utf-8"))
    OUT_PATH.write_text(build_markdown(data), encoding="utf-8")
    print(f"Wrote {OUT_PATH.relative_to(ROOT)} ({len(data.get('cases', {}))} cases).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
